import console from "node:console";
import process from "node:process";
import { access, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, URL } from "node:url";
import { generateCatalog } from "../apps/docs/scripts/catalog.mjs";

const root = fileURLToPath(new URL("../", import.meta.url));
const specPath = "docs/specs/SPEC-react-components.md";
const matrixPath = path.join(root, "docs/catalog-evidence.md");
const spec = await readFile(path.join(root, specPath), "utf8");
const section = spec.split("## Component families")[1]?.split("## API")[0];
if (!section) throw new Error("Missing approved component-family table");

const expected = section.split("\n").flatMap((line) => {
  const [, family, names] = line.split("|").map((value) => value.trim());
  if (!family || !names || family === "Family" || family.startsWith("---"))
    return [];
  return names.split(", ").map((title) => ({
    family,
    title,
    id:
      title === "Select Native"
        ? "native-select"
        : title.toLowerCase().replaceAll(" ", "-"),
  }));
});

const catalog = new Map(
  (await generateCatalog()).map((item) => [item.id, item]),
);
if (
  catalog.size !== expected.length ||
  new Set(expected.map(({ id }) => id)).size !== expected.length
) {
  throw new Error(
    `Approved catalog and registry differ: ${expected.length} approved, ${catalog.size} installed`,
  );
}

const formatLink = (label, file) => `[${label}](../${file})`;
const rows = await Promise.all(
  expected.map(async ({ family, id, title }) => {
    const entry = catalog.get(id);
    if (!entry) throw new Error(`Missing registry entry: ${id}`);
    const docs = `apps/docs/content/components/${id}.mdx`;
    const text = await readFile(path.join(root, docs), "utf8");
    if (!text.includes(`ecentry add ${id}`) || !text.includes("## Preview")) {
      throw new Error(`Missing install command or preview: ${id}`);
    }
    const source = `packages/react/src/components/${id}`;
    const contracts = (await readdir(path.join(root, source)))
      .filter((file) => /\.test\.tsx?$/.test(file))
      .sort();
    if (!contracts.length) throw new Error(`Missing component tests: ${id}`);
    const browser = `tests/e2e/${id}.spec.ts`;
    await access(path.join(root, browser));
    return [
      title,
      family,
      formatLink("Guide and preview", docs),
      `[${entry.api.map(({ name }) => name).join(", ") || "Native attributes"}](https://ecentry.dev${entry.href}#api-reference)`,
      contracts
        .map((file) => formatLink("Unit", `${source}/${file}`))
        .join(", "),
      formatLink("Chromium", browser),
      formatLink(entry.version, `registry/react/${id}/manifest.json`),
    ].join(" | ");
  }),
);

const matrix = [
  "<!-- Generated by npm run catalog:audit -- --write. -->",
  "# React catalog evidence",
  "",
  "The approved component list comes from the [React component specification](specs/SPEC-react-components.md). The guide and API links document usage, variants, and states. Both consumer fixtures install and compile the full registry. Unit and browser links point to the tests that exercise each component.",
  "",
  "| Component | Family | Documentation | Public API | Contract tests | Browser flow | Source manifest |",
  "| --- | --- | --- | --- | --- | --- | --- |",
  ...rows.map((row) => `| ${row} |`),
  "",
].join("\n");

if (process.argv.includes("--write")) {
  await writeFile(matrixPath, matrix);
} else if ((await readFile(matrixPath, "utf8")) !== matrix) {
  throw new Error(
    "Catalog evidence is stale. Run npm run catalog:audit -- --write.",
  );
}
console.log(`Audited ${expected.length} React catalog entries`);
